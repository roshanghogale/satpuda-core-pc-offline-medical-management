_TRADING_CACHE: dict = {}


def _shop_already_trading() -> bool:
    """Has any shop on this computer sold or bought anything yet?

    A fresh install has not. This is the one condition a local delete cannot
    undo, so it is what keeps the starter window from becoming a renewable
    licence for a shop that is actually running (see the block above).

    Answers False for anything it cannot read: a starter window is never
    refused because a file was busy.
    """
    if "v" in _TRADING_CACHE:
        return _TRADING_CACHE["v"]
    found = False
    try:
        import sqlite3

        from core import store_manager

        for st in (store_manager.list_stores() or []):
            key = str((st or {}).get("store_key") or "")
            if not key:
                continue
            try:
                path = store_manager.get_store_db_path(key)
            except Exception:
                continue
            if not path or not os.path.exists(path):
                continue
            try:
                con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
            except Exception:
                continue
            try:
                for table in ("sales", "purchases"):
                    try:
                        if con.execute(f"SELECT 1 FROM {table} LIMIT 1").fetchone():
                            found = True
                            break
                    except Exception:
                        continue
            finally:
                try:
                    con.close()
                except Exception:
                    pass
            if found:
                break
    except Exception:
        found = False
    _TRADING_CACHE["v"] = found
    return found


def seal_ever_stored() -> bool:
    """Has a verified licence ever been accepted on this computer?"""
    try:
        from core.license_manager import _read_activation

        record = _read_activation() or {}
    except Exception:
        return False
    if record.get("lic_seen"):
        return True
    try:
        if int(record.get("lic_ser") or 0) > 0:
            return True
    except Exception:
        pass
    # And the obvious one: a licence sitting on the disk right now.
    return bool(read_seal())


# ── Storage ───────────────────────────────────────────────────────────────────
def read_seal() -> str:
    path = seal_path()
    try:
        if not os.path.isfile(path):
            return ""
        with open(path, encoding="utf-8-sig") as fh:
            return fh.read().strip()
    except Exception:
        return ""


def store_seal(blob: str, *, fresh: bool = False) -> dict | None:
    """Verify a blob and keep it. Returns the payload, or None if it is no good.

    ``fresh`` means it came from the server just now, so it sets the ratchet
    rather than being judged by it.
    """
    payload = verify_blob(blob)
    if not payload:
        return None
    if not binding_matches(payload):
        return None
    serial = int(payload.get("ser") or 0)
    if fresh:
        _write_serial_floor(serial)
    elif serial < _read_serial_floor():
        return None
    # From here on this computer has held a real licence, so the fresh-install
    # window is closed to it for good -- even if the file is deleted a minute
    # from now. Recorded BEFORE the write, because a licence that verified is a
    # licence this PC has seen whether or not the disk accepted the file.
    _mark_seal_seen()
    try:
        path = seal_path()
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(str(blob).strip())
        os.replace(tmp, path)
    except Exception:
        # A blob that could not be written is still a valid licence for this run.
        pass
    return payload


def clear_seal() -> None:
    try:
        os.remove(seal_path())
    except Exception:
        pass


def local_payload() -> tuple[dict | None, str]:
    """(payload, state) for what is on this disk right now. No network."""
    blob = read_seal()
    if not blob:
        return None, STATE_MISSING
    payload = verify_blob(blob)
    if not payload:
        return None, STATE_TAMPERED
    if not binding_matches(payload):
        return None, STATE_TAMPERED
    if int(payload.get("ser") or 0) < _read_serial_floor():
        return None, STATE_TAMPERED
    return payload, STATE_SIGNED


# ── The grace window for shops that were already running ──────────────────────
def _activation_predates_cutover() -> bool:
    """Was this PC activated by a build that had no seal to fetch?

    No activation record at all is NOT a legacy install. That matters: wiping
    AppData is exactly how the delete trick is performed, and it takes
    activation.dat with it -- so the wiped machine lands in "no licence, fetch
    one" on its first launch rather than being handed the upgrade allowance.
    """
    try:
        from core.license_manager import _read_activation

        data = _read_activation() or {}
    except Exception:
        return False
    if not data:
        return False
    day = _as_date(data.get("date"))
    if day is None:
        # A record with no date was written by a build old enough to predate the
        # seal by definition.
        return True
    cutover = _as_date(SEAL_CUTOVER)
    return bool(cutover and day < cutover)


def in_legacy_grace() -> bool:
    """A shop that was running before the seal existed, still inside the window."""
    until = _as_date(LEGACY_GRACE_UNTIL)
    if until is None or _today() > until:
        return False
    return _activation_predates_cutover()


# ── The fresh install that never reached the server ───────────────────────────
def fresh_install_window() -> dict | None:
    """The starter licence for a PC activated here that has never had one.

    Returns ``{"activation_date", "expiry_date", "lapsed"}``, or None when this
    computer does not qualify. See FRESH_INSTALL_DAYS above for why each of
    these conditions is here; every one of them is load-bearing.

    Note what it does NOT do: it never extends a real expiry. The moment a
    signed licence exists, ``seal_state`` answers from the blob and never
    consults this at all -- and once one has EVER existed here, this refuses
    for the life of the activation record.
    """
    if seal_ever_stored():
        return None
    if _shop_already_trading():
        # Not a fresh install: this computer has bills on it. Whatever went
        # wrong with its licence, three free days is not the answer.
        return None
    try:
        from core.license_manager import _read_activation

        record = _read_activation() or {}
    except Exception:
        return None
    if not record:
        # No activation record: a wiped AppData, or a machine that never
        # finished setting up. Neither is a shop that has just been activated.
        return None
    # The FIRST activation this computer made, not the latest one: a
    # re-activation must not buy another window. Both places are read and the
    # earlier one wins, so deleting either file changes nothing.
    day = _as_date(record.get("first_date") or record.get("date"))
    marked = _as_date((_read_starter_marker() or {}).get("first"))
    if marked is not None and (day is None or marked < day):
        day = marked
    cutover = _as_date(SEAL_CUTOVER)
    if day is None or cutover is None or day < cutover:
        # Undated or pre-cutover records belong to the legacy path, which has
        # its own window and its own rules.
        return None
    if day > _today():
        # A clock set forward, or a record carried from another machine. Not a
        # licence to hand out days on.
        return None
    expiry = day + timedelta(days=FRESH_INSTALL_DAYS)
    _write_starter_marker(day)
    return {
        "activation_date": day.isoformat(),
        "expiry_date": expiry.isoformat(),
        "lapsed": _today() >= expiry,
    }


# ── Fetching ──────────────────────────────────────────────────────────────────
_FETCH_LOCK = threading.RLock()
_LAST_FETCH_AT = 0.0
_FETCH_EVERY_SEC = 60.0
_FETCH_THREAD: threading.Thread | None = None


def _binding_body() -> dict:
    from core.trial_activation import device_id, machine_id

    return {
        "machine_id": machine_id(),
        "device_id": device_id(),
        "hw_parts": binding_digests(),
    }


def _paired() -> bool:
    """Does this PC still hold an SC- key? Cheap, and no network."""
    try:
        from core.store_link import get_local_android_key

        return bool((get_local_android_key() or "").strip())
    except Exception:
        return False


def _fetch_seal_now(*, timeout: float) -> None:
    """The fetch itself. Runs on a worker thread; stores what it gets.

    Two ways in, tried in order, and the SECOND is the one this whole change
    exists for:

      1. With the store's own token, when this PC still has its SC- key.
      2. By hardware fingerprint, when it does not -- which is precisely the
         state a wiped AppData leaves behind. The server looks the machine up in
         its trial log and hands back the SAME licence it granted the first time.
         That is why deleting the file does not reset the date.
    """
    from core import server_api as api

    try:
        body = _binding_body()
    except Exception:
        return

    if _paired():
        # Only when there IS a key. store_token_for_active pairs over the
        # network when the cached token has lapsed, and an Offline shop that
        # never had a key would pay for that round trip to be told what it
        # already knows.
        try:
            token = (api.store_token_for_active() or "").strip()
        except Exception:
            token = ""
        if token:
            try:
                data = api.get_signed_license(token, body, timeout=timeout) or {}
                if store_seal(str(data.get("signed") or ""), fresh=True):
                    return
            except Exception:
                pass

    try:
        data = api.recover_signed_license(body, timeout=timeout) or {}
        store_seal(str(data.get("signed") or ""), fresh=True)
    except Exception:
        pass


def fetch_seal(
    *, timeout: float = 20.0, force: bool = False, wait: float | None = None
) -> dict | None:
    """Ask the server for this store's signed expiry. Returns the payload or None.

    ON A WORKER THREAD, with a bounded wait, because this is called from the
    LAUNCH path. A shop with no internet is exactly the shop that reaches here
    with no licence file, and a socket that takes its own sweet time to fail
    would hold the splash screen for as long as it liked. The worker keeps going
    after the wait expires and stores whatever it gets, so a slow answer is not
    a lost one -- the next licence read picks it up.

    ``wait=0`` starts the worker and returns immediately. That is for the
    OPPORTUNISTIC refresh -- the one taken while the server is already answering
    an Online licence read -- which improves the next offline launch and must
    never make this one slower.

    Rate-limited to once a minute per process: the licence status is polled by
    the desktop's status endpoint several times a second, and an unguarded call
    there would walk a shop into the server's own limiter and then tell it that
    it had been refused.
    """
    global _LAST_FETCH_AT, _FETCH_THREAD
    with _FETCH_LOCK:
        now = time.time()
        running = _FETCH_THREAD is not None and _FETCH_THREAD.is_alive()
        if not running:
            if not force and (now - _LAST_FETCH_AT) < _FETCH_EVERY_SEC:
                return None
            _LAST_FETCH_AT = now
            _FETCH_THREAD = threading.Thread(
                target=_fetch_seal_now,
                kwargs={"timeout": timeout},
                name="satpuda-licence-fetch",
                daemon=True,
            )
            _FETCH_THREAD.start()
        worker = _FETCH_THREAD

    hold = float(timeout) if wait is None else float(wait)
    if worker is not None and hold > 0:
        worker.join(max(0.5, hold))
    elif worker is not None:
        return None
    payload, state = local_payload()
    return payload if state == STATE_SIGNED else None


def ensure_seal(*, timeout: float = 8.0) -> tuple[dict | None, str]:
    """What this PC's licence is, fetching one if the local answer is not good.

    The short timeout is deliberate. This runs on the launch path, and a shop
    with no internet must not watch a splash screen while a socket times out --
    it is inside the grace window or it is not, and neither answer improves by
    waiting.
    """
    payload, state = local_payload()
    if state == STATE_SIGNED:
        if not payload_blocks(payload):
            return payload, state
        # THE LICENCE SAYS NO. Ask the server before turning the shop away.
        #
        # This is the one moment a refresh is worth a round trip: the vendor has
        # extended the date on the server and told the shopkeeper to connect the
        # internet, and without this the app would keep reading the stale blob
        # off its own disk and keep refusing. It is also the only way back for an
        # Offline shop whose trial has run out, because the Administrator screen
        # that could change the date is behind the block. Rate-limited to once a
        # minute like every other fetch, so a blocked shop does not hammer
        # anything while it waits.
        fresher = fetch_seal(timeout=timeout)
        return (fresher, STATE_SIGNED) if fresher else (payload, state)
    if not keys_configured():
        # No public key was compiled into this build, so nothing could ever
        # verify. Enforcing here would block every shop at once over a build
        # mistake. Report the state and let the caller fall back to the old
        # rules; test_the_build_carries_a_licence_key is what stops such a build
        # being shipped.
        return None, state
    if state == STATE_MISSING:
        window = fresh_install_window()
        if window and not window["lapsed"]:
            # Inside the starter window the till opens either way, so waiting
            # for the socket buys nothing. Start the fetch and walk away: the
            # shop this happens to is the shop with no internet, and it must not
            # watch a splash screen for the whole timeout every morning for
            # three days. A slow answer is not a lost one -- the worker stores
            # what it gets and the next licence read picks it up.
            fetch_seal(timeout=timeout, wait=0.0)
            return None, state
    fetched = fetch_seal(timeout=timeout)
    if fetched:
        return fetched, STATE_SIGNED
    return None, state


# ── What the rest of the app asks ─────────────────────────────────────────────
def seal_state(*, fetch: bool = True, timeout: float = 8.0) -> dict:
    """The licence, and whether it blocks. The one function callers need.

    ``blocked`` is why this is not simply a date:

      * ``signed``   -- the blob decides, exactly as the server wrote it.
      * ``legacy``   -- a shop that predates the seal, inside the grace window.
        The caller applies the OLD rules; nothing here blocks it.
      * ``missing`` / ``tampered`` -- blocked, and the reason is not "expired".
        The shop is told to connect the internet once. It is deliberately NOT an
        expiry: expiry in Offline mode deletes activation.dat to force the
        vendor's re-activation, and doing that to a shop whose file merely went
        missing would destroy the one record that says it was ever activated.
    """
    payload, state = (ensure_seal(timeout=timeout) if fetch else local_payload())
    if state == STATE_SIGNED and payload:
        return {
            "state": STATE_SIGNED,
            "blocked": bool(payload_blocks(payload)),
            "reason": payload_block_reason(payload),
            "expiry_date": str(payload.get("exp") or ""),
            "activation_date": str(payload.get("act") or ""),
            "enabled": bool(payload.get("een")),
            "apply_expiry_check": bool(payload.get("aec", True)),
            "is_active": bool(payload.get("act_ok", True)),
            "serial": int(payload.get("ser") or 0),
            "message": "",
            "payload": payload,
        }
    if in_legacy_grace():
        return {
            "state": STATE_LEGACY,
            "blocked": False,
            "reason": "",
            "expiry_date": "",
            "activation_date": "",
            "enabled": False,
            "apply_expiry_check": True,
            "is_active": True,
            "serial": 0,
            "message": NEEDS_INTERNET_MESSAGE,
            "payload": None,
        }
    # A fresh install whose sign-up never reached the server. It opens on its
    # starter window and then EXPIRES -- reason "expired", not "needs_internet",
    # because the shop is out of time rather than out of a file. A tampered blob
    # is never a fresh install.
    if state == STATE_MISSING:
        window = fresh_install_window()
        if window:
            lapsed = bool(window["lapsed"])
            return {
                "state": STATE_FRESH,
                "blocked": lapsed,
                "reason": "expired" if lapsed else "",
                "expiry_date": window["expiry_date"],
                "activation_date": window["activation_date"],
                "enabled": True,
                "apply_expiry_check": True,
                "is_active": True,
                "serial": 0,
                "message": (
                    FRESH_INSTALL_LAPSED_MESSAGE.format(days=FRESH_INSTALL_DAYS)
                    if lapsed
                    else FRESH_INSTALL_MESSAGE.format(
                        days=FRESH_INSTALL_DAYS, until=window["expiry_date"]
                    )
                ),
                "payload": None,
            }
    if not keys_configured():
        # See ensure_seal: an unkeyed build must not block the fleet.
        return {
            "state": STATE_LEGACY,
            "blocked": False,
            "reason": "",
            "expiry_date": "",
            "activation_date": "",
            "enabled": False,
            "apply_expiry_check": True,
            "is_active": True,
            "serial": 0,
            "message": "",
            "payload": None,
        }
    return {
        "state": state,
        "blocked": True,
        "reason": "needs_internet",
        "expiry_date": "",
        "activation_date": "",
        "enabled": False,
        "apply_expiry_check": True,
        "is_active": True,
        "serial": 0,
        "message": TAMPERED_MESSAGE if state == STATE_TAMPERED else NEEDS_INTERNET_MESSAGE,
        "payload": None,
    }


def payload_blocks(payload: dict) -> bool:
    """Does this signed licence deny access today?"""
    if not isinstance(payload, dict):
        return True
    if payload.get("act_ok") is False:
        return True
    if not bool(payload.get("aec", True)):
        return False
    if not bool(payload.get("een")):
        return False
    expiry = _as_date(payload.get("exp"))
    if expiry is None:
        return False
    return _today() >= expiry


def payload_block_reason(payload: dict) -> str:
    if not isinstance(payload, dict):
        return "needs_internet"
    if payload.get("act_ok") is False:
        return "access_disabled"
    return "expired" if payload_blocks(payload) else ""


def issued_at(payload: dict) -> str:
    try:
        return datetime.fromtimestamp(int(payload.get("iat") or 0), timezone.utc).isoformat()
    except Exception:
        return ""
