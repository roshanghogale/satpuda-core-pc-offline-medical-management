# ── RSA verification, twice ───────────────────────────────────────────────────
#
# SHA-256 DigestInfo prefix, from RFC 8017 section 9.2 notes. Fixed bytes: this
# is the only digest algorithm the seal uses, so there is nothing to negotiate
# and nothing for a caller to steer.
_SHA256_DIGESTINFO = bytes.fromhex("3031300d060960864801650304020105000420")


def _der_read_len(buf: bytes, i: int) -> tuple[int, int]:
    n = buf[i]
    i += 1
    if n < 0x80:
        return n, i
    count = n & 0x7F
    if count == 0 or count > 4:
        raise ValueError("bad DER length")
    val = int.from_bytes(buf[i:i + count], "big")
    return val, i + count


def _rsa_numbers(spki_der: bytes) -> tuple[int, int]:
    """(modulus, exponent) out of a SubjectPublicKeyInfo DER.

    A deliberately small, strict reader. It walks the exact structure an RSA
    SPKI has and refuses anything else, rather than being a general ASN.1 parser
    -- the input is a constant compiled into this build, not something a caller
    supplies, so tolerance would buy nothing and cost surface.
    """
    i = 0
    if spki_der[i] != 0x30:
        raise ValueError("SPKI: expected SEQUENCE")
    _, i = _der_read_len(spki_der, i + 1)
    # AlgorithmIdentifier — skipped whole; the key set is ours.
    if spki_der[i] != 0x30:
        raise ValueError("SPKI: expected AlgorithmIdentifier")
    alg_len, j = _der_read_len(spki_der, i + 1)
    i = j + alg_len
    if spki_der[i] != 0x03:
        raise ValueError("SPKI: expected BIT STRING")
    bit_len, i = _der_read_len(spki_der, i + 1)
    if spki_der[i] != 0x00:
        raise ValueError("SPKI: unexpected unused bits")
    i += 1
    inner = spki_der[i:i + bit_len - 1]
    # RSAPublicKey ::= SEQUENCE { modulus INTEGER, publicExponent INTEGER }
    k = 0
    if inner[k] != 0x30:
        raise ValueError("RSAPublicKey: expected SEQUENCE")
    _, k = _der_read_len(inner, k + 1)
    vals = []
    for _ in range(2):
        if inner[k] != 0x02:
            raise ValueError("RSAPublicKey: expected INTEGER")
        n, k = _der_read_len(inner, k + 1)
        vals.append(int.from_bytes(inner[k:k + n], "big"))
        k += n
    return vals[0], vals[1]


def _verify_stdlib(spki_der: bytes, message: bytes, signature: bytes) -> bool:
    """RSASSA-PKCS1-v1_5 / SHA-256 verify, standard library only.

    The whole of it: raise the signature to the public exponent, then compare the
    result to the block that a correct signature MUST have produced. Whole-block
    equality, not a parse -- there is no "read the padding and see if it looks
    right" step to be lenient about.
    """
    try:
        n, e = _rsa_numbers(spki_der)
    except Exception:
        return False
    k = (n.bit_length() + 7) // 8
    if len(signature) != k:
        return False
    s = int.from_bytes(signature, "big")
    if s >= n:
        return False
    em = pow(s, e, n).to_bytes(k, "big")
    digest = hashlib.sha256(message).digest()
    tail = _SHA256_DIGESTINFO + digest
    ps_len = k - 3 - len(tail)
    if ps_len < 8:
        return False
    expected = b"\x00\x01" + b"\xff" * ps_len + b"\x00" + tail
    return hmac.compare_digest(em, expected)


def _verify_cryptography(spki_der: bytes, message: bytes, signature: bytes) -> bool | None:
    """The same check through ``cryptography``. None when it is not available."""
    try:
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import padding, rsa
    except Exception:
        return None
    try:
        key = serialization.load_der_public_key(spki_der)
        if not isinstance(key, rsa.RSAPublicKey):
            return False
        key.verify(signature, message, padding.PKCS1v15(), hashes.SHA256())
        return True
    except Exception:
        return False


def _verify_raw(kid: str, message: bytes, signature: bytes) -> bool:
    der_b64 = _PUBLIC_KEYS.get(str(kid or ""))
    if not der_b64:
        return False
    try:
        spki = base64.b64decode(der_b64)
    except Exception:
        return False
    via_lib = _verify_cryptography(spki, message, signature)
    if via_lib is not None:
        return bool(via_lib)
    return _verify_stdlib(spki, message, signature)


# One entry, keyed by the blob text. local_payload() runs on a status endpoint
# the desktop polls several times a second, and there is no reason to redo an
# RSA verification on bytes that have not changed. Cleared implicitly whenever
# the file does change, because the key IS the file's content.
_VERIFY_MEMO: dict[str, dict | None] = {}


def verify_blob(blob: str) -> dict | None:
    """The payload of a genuine blob, or None. Signature only — not the binding."""
    text = str(blob or "").strip()
    if text in _VERIFY_MEMO:
        memo = _VERIFY_MEMO[text]
        return dict(memo) if memo else None
    result = _verify_blob_uncached(text)
    if len(_VERIFY_MEMO) > 8:
        _VERIFY_MEMO.clear()
    _VERIFY_MEMO[text] = dict(result) if result else None
    return result


def _verify_blob_uncached(text: str) -> dict | None:
    parts = text.split(".")
    if len(parts) != 3 or parts[0] != SEAL_PREFIX:
        return None
    try:
        payload = json.loads(_b64url_decode(parts[1]).decode("utf-8"))
        signature = _b64url_decode(parts[2])
    except Exception:
        return None
    if not isinstance(payload, dict):
        return None
    if str(payload.get("alg") or "") != "RS256":
        return None
    message = f"{parts[0]}.{parts[1]}".encode("ascii")
    if not _verify_raw(payload.get("kid"), message, signature):
        return None
    return payload


# ── The machine binding ───────────────────────────────────────────────────────
_HW_KEYS = ("cpu", "board", "sysuuid", "disk")


def binding_digests() -> dict:
    """SHA-256 of each hardware component this PC can read.

    Digests, not the serial numbers. The comparison is exactly as sharp and the
    shop's disk and board serials never travel to the server or sit in its logs.
    A component that cannot be read contributes nothing rather than the digest of
    an empty string -- which would be the SAME value on every unreadable machine
    and would match all of them against each other.
    """
    try:
        from core.license_manager import _hardware_parts

        parts = _hardware_parts()
    except Exception:
        parts = {}
    out = {}
    for key in _HW_KEYS:
        val = str((parts or {}).get(key) or "").strip()
        if val:
            out[key] = hashlib.sha256(val.encode("utf-8")).hexdigest()
    return out


def binding_matches(payload: dict) -> bool:
    """Is this blob's machine THIS machine?

    Tolerant in exactly the way ``hardware_matches`` is tolerant, and for the
    same reason: this code base has already been burned by a fingerprint that
    moved when a Windows update installed a virtual adapter or a WMIC call timed
    out, and a shop locked out of its own till by a disk swap is a worse outcome
    than a licence one component looser. So: every component that BOTH sides can
    read must match, except one.

    What that still refuses is a copy. Two different computers differ in all four
    components, not one, so a blob carried to another PC on a USB stick fails.

    When nothing can be read here, the blob's device id is the fallback rather
    than a free pass. ``hardware_matches`` deliberately returns True in that case
    -- it would rather let a shop into its own till than lock it out -- but the
    same reasoning does not carry over: a blob that matches any computer with an
    unreadable fingerprint would be a licence worth copying.
    """
    if not isinstance(payload, dict):
        return False
    saved = payload.get("hwp")
    now = binding_digests()
    if isinstance(saved, dict) and saved and now:
        known = matched = 0
        for key in _HW_KEYS:
            was, is_ = str(saved.get(key) or ""), str(now.get(key) or "")
            if not was or not is_:
                continue
            known += 1
            if hmac.compare_digest(was, is_):
                matched += 1
        if known:
            return matched >= known - 1 if known > 1 else matched == 1
    # Either the blob carries no components or this machine can read none.
    saved_hw = str(payload.get("hw") or "")
    if saved_hw and now:
        try:
            from core.license_manager import _get_hardware_hash

            if hmac.compare_digest(saved_hw, str(_get_hardware_hash() or "")):
                return True
        except Exception:
            pass
    saved_dev = str(payload.get("dev") or "")
    if saved_dev:
        try:
            from core.trial_activation import device_id

            return hmac.compare_digest(saved_dev, str(device_id() or ""))
        except Exception:
            return False
    return False


# ── The rollback ratchet ──────────────────────────────────────────────────────
#
# A blob stays valid forever -- that is what a signature means. So a shop whose
# expiry the vendor SHORTENS could keep last year's generous blob and put it back.
# The counter is a high-water mark: the highest serial (the store row's
# updated_at, in seconds) this PC has ever seen. A blob read FROM DISK that is
# older than the mark is refused; a blob that arrives FRESH from the server is
# always accepted and resets the mark, so a restored database cannot lock a fleet
# out.
#
# The mark lives inside activation.dat, which is Fernet-encrypted and whose
# deletion forces a full re-activation. Deleting it to escape the ratchet
# therefore costs an activation, and an activation goes through the server.


def _read_serial_floor() -> int:
    try:
        from core.license_manager import _read_activation

        return int((_read_activation() or {}).get("lic_ser") or 0)
    except Exception:
        return 0


def _write_serial_floor(serial: int) -> None:
    try:
        from core.license_manager import _activation_path, _encrypt, _read_activation

        record = dict(_read_activation() or {})
        if not record:
            return
        if int(record.get("lic_ser") or 0) == int(serial):
            return
        record["lic_ser"] = int(serial)
        with open(_activation_path(), "wb") as fh:
            fh.write(_encrypt(record))
    except Exception:
        pass


