"""The signed licence — "the seal". The expiry stops being a local fact.

WHAT WAS WRONG
--------------
A shop's expiry lived in one file on the shop's own PC, ``expiry.dat``, and the
app believed whatever it found there. Two ways to profit from that, and neither
needed any skill:

  * DELETE the file. ``_read_expiry()`` returns ``{}``, ``check_expiry()`` reads
    that as "no restriction configured" and returns False. Reinstalling gives
    the same result, because the installer's sign-up is refused for a computer
    that has already had its trial and the Offline path then activates locally
    with no expiry at all. The licence was one keystroke from permanent.
  * EDIT the file. It is encrypted, but with ``_SECRET`` -- a constant compiled
    into every copy of the build. Anyone willing to open the exe can write a new
    date rather than merely delete the old one.

And ``expiry_config.json``, which decides whether expiry is consulted at all, is
plain JSON. ``{"apply_expiry_check": false}`` in a text editor turned the whole
mechanism off.

THE OWNER'S DECISION
--------------------
Once an expiry is set at first activation -- Online or Offline -- it must not
change except from the server or from the software's own Administrator settings.
Deleting the file and reinstalling must not reset it: *"delete kelch tr aapn
internet suru karnyas sangu shakto mhanaje tech file punha yeil"* -- if they
delete it we can tell them to turn the internet on, and the same file comes back.
An offline shop needing internet once is accepted, because the installer already
needs it to download.

THE SHAPE
---------
The server decides the expiry and SIGNS it. The desktop keeps the signed blob and
verifies it before believing a word of it.

  * EDIT the date -> the signature fails -> blocked immediately.
  * COPY the blob to another PC -> the machine binding fails -> blocked.
  * DELETE the blob -> not "no restriction". No licence. The app asks for
    internet once and fetches the SAME blob back, because the server -- not the
    file -- is where the expiry lives.

THE CRYPTO, AND WHY THIS ONE
----------------------------
RSA-2048, RSASSA-PKCS#1 v1.5, SHA-256, over the exact ASCII bytes transmitted.

  * ASYMMETRIC. The build carries only the PUBLIC key. Decompiling the exe yields
    a key that can check a licence and cannot write one. An HMAC would put the
    minting secret inside every installer that can be downloaded, which is the
    same mistake the server already refused to make when it built
    ``/api/provision/trial`` rather than shipping the vendor's administrator
    password in the build.

  * PKCS#1 v1.5 rather than Ed25519 or PSS, and the reason is this file. The
    verifier has to work when ``cryptography`` does not import -- a case this
    code base has already been bitten by and still carries a fallback for (see
    ``_get_fernet`` in license_manager). A hand-written Ed25519 verifier is
    eighty lines of modular arithmetic with real traps: cofactor, canonical
    encodings, malleability. A PKCS#1 v1.5 verifier is ``pow(sig, e, n)`` and one
    comparison against the expected block -- twenty lines, no attacker-steerable
    branch, and because it compares the WHOLE block rather than parsing it, the
    lenient-parser family of bugs (Bleichenbacher '06) cannot exist in it. One
    algorithm, two implementations, no weak mode to fall into. ``_verify_raw``
    below prefers ``cryptography`` and falls back to ``_verify_stdlib``; a test
    runs both against the same blobs.

  * The signature covers ``SATPUDA1.<base64url(payload)>`` as ASCII, JWS-style,
    so no canonical-JSON agreement is needed between Node and Python. Key order,
    spacing and unicode escaping cannot break a signature.

WHAT THIS FILE WILL NOT DO
--------------------------
It will not invent an expiry, and it will not treat a missing one as permission.
The only two answers it gives are "here is a licence the server signed" and "this
computer needs internet once".
"""
